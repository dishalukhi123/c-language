#include<stdio.h>
int main()
{
    int a,b;

    printf("Enter a number of A :");
    scanf("%d",&a);

    printf("Enter a number of B :");
    scanf("%d",&b);

    printf("your addition value : %d\n",a+b);
    printf("your subtraction value : %d\n",a-b);
    printf("your multiplication value : %d\n",a*b);
    printf("your division value : %d\n",a/b);
    printf("your modulo value : %d\n",a%b);

    
    return 0;
}
